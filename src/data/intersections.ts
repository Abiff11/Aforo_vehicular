function createIntersection(mapNumber: number, latitude: number, longitude: number): Intersection {
  const padded = String(mapNumber).padStart(3, '0');

  return {
    id: `INT-${padded}`,
    mapNumber,
    name: intersectionNames[mapNumber],
    municipality: 'Oaxaca de Juarez',
    locality: 'Oaxaca de Juarez',
    verificationStatus: mapNumber <= 8 ? 'pending' : 'verified',
    latitude,
    longitude,
    notes: 'Nombre sugerido con vialidades cercanas de OpenStreetMap; puede ajustarse si el levantamiento confirma otra nomenclatura.',
  };
}

